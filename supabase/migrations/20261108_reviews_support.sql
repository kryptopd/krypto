-- KRYPTO: avaliações moderadas e central de atendimento pós-venda.
create extension if not exists pgcrypto;

create table if not exists public.reviews (
 id bigint generated by default as identity primary key,
 customer_name text not null check (char_length(customer_name) between 1 and 100),
 email text not null,
 product_name text not null check (char_length(product_name) between 1 and 140),
 rating smallint not null check (rating between 1 and 5),
 comment text not null check (char_length(comment) between 10 and 1200),
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 moderated_at timestamptz,
 spam_flag text,
 created_at timestamptz not null default now()
);
alter table public.reviews add column if not exists spam_flag text;
create index if not exists reviews_status_created_idx on public.reviews(status,created_at desc);
alter table public.reviews enable row level security;
drop policy if exists "Public can read approved reviews" on public.reviews;
create policy "Public can read approved reviews" on public.reviews for select to anon, authenticated using (status='approved');
-- Escritas e moderação passam exclusivamente pelas funções server-side com service role.

create table if not exists public.support_requests (
 id bigint generated by default as identity primary key,
 public_code text not null unique default upper(substr(encode(gen_random_bytes(6),'hex'),1,10)),
 customer_name text not null,
 email text not null,
 phone text not null,
 order_code text not null,
 purchase_date date not null,
 reason text not null check (reason in ('Troca','Devolução','Reembolso','Produto com defeito','Produto incorreto','Outro')),
 comment text not null check (char_length(comment) between 1 and 2000),
 photo_paths text[] not null default '{}' check (cardinality(photo_paths)<=3),
 status text not null default 'open' check (status in ('open','in_review','resolved','rejected')),
 resolved_at timestamptz,
 created_at timestamptz not null default now()
);
create index if not exists support_requests_status_created_idx on public.support_requests(status,created_at desc);
alter table public.support_requests enable row level security;
-- Solicitações e anexos são privados; acesso somente via API autenticada do painel.

