-- 5) Ajusta o estoque de uma variação dentro do array jsonb (delta pode ser negativo).
create or replace function public.krypto_variant_adjust(p_variants jsonb, p_color text, p_size text, p_delta integer)
returns jsonb language sql immutable
as $$
  select coalesce(jsonb_agg(
    case when t.e->>'color' = p_color and t.e->>'size' = p_size
      then jsonb_set(t.e, '{stock}', to_jsonb(greatest(0, (t.e->>'stock')::integer + p_delta)))
      else t.e end
    order by t.ord), '[]'::jsonb)
  from jsonb_array_elements(p_variants) with ordinality as t(e, ord);
$$;

-- 6) Quando um pedido libera o estoque (cancelado, expirado, recusado, reembolsado), devolve também a variação.
--    As funções que já devolvem o total continuam iguais; aqui só acertamos a variação e refazemos o total.
create or replace function public.krypto_restore_variants()
returns trigger language plpgsql security definer set search_path = public
as $$
declare v_item jsonb; v_p public.products%rowtype; v_new jsonb;
begin
  if new.inventory_released = true and old.inventory_released = false then
    for v_item in select value from jsonb_array_elements(new.items) loop
      select * into v_p from public.products where id = (v_item->>'product_id')::bigint for update;
      if found and jsonb_array_length(v_p.variants) > 0 then
        v_new := public.krypto_variant_adjust(v_p.variants, coalesce(v_item->>'color',''), coalesce(v_item->>'size',''),
                   greatest(0, coalesce((v_item->>'quantity')::integer, 0)));
        update public.products set variants = v_new,
          stock = (select coalesce(sum((e->>'stock')::integer), 0) from jsonb_array_elements(v_new) e)
         where id = v_p.id;
      end if;
    end loop;
  end if;
  return new;
end;
$$;
drop trigger if exists krypto_restore_variants_trg on public.orders;
create trigger krypto_restore_variants_trg after update of inventory_released on public.orders
  for each row execute function public.krypto_restore_variants();

-- 7) Criação de pedido: confere/baixa o estoque da variação e aplica o desconto PIX (calculado aqui, no servidor).
drop function if exists public.create_krypto_order_v2(jsonb, jsonb, integer, boolean, uuid);
create or replace function public.create_krypto_order_v2(
  p_customer jsonb, p_items jsonb, p_shipping_cents integer,
  p_privacy_acknowledged boolean default false, p_user_id uuid default null,
  p_pix_discount_percent numeric default 0
)
returns table(public_id text, total_cents integer, subtotal_cents integer, shipping_cents integer, discount_cents integer, order_items jsonb)
language plpgsql security definer set search_path = public
as $$
declare
  v_line record;
  v_product public.products%rowtype;
  v_subtotal integer := 0;
  v_discount integer := 0;
  v_total integer;
  v_public_id text;
  v_items jsonb := '[]'::jsonb;
  v_vstock integer;
  v_new jsonb;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'INVALID_ITEMS';
  end if;
  if p_shipping_cents is null or p_shipping_cents < 0 or p_shipping_cents > 1000000 then raise exception 'INVALID_SHIPPING'; end if;
  if p_privacy_acknowledged is distinct from true then raise exception 'PRIVACY_CONSENT_REQUIRED'; end if;

  for v_line in
    select (e->>'product_id')::bigint as product_id, coalesce(e->>'size', '') as size,
           coalesce(e->>'color', '') as color, (e->>'quantity')::integer as quantity
      from jsonb_array_elements(p_items) e
     order by 1, 2, 3
  loop
    if v_line.quantity is null or v_line.quantity < 1 or v_line.quantity > 10 then raise exception 'INVALID_QUANTITY'; end if;
    select * into v_product from public.products where id = v_line.product_id and active = true for update;
    if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
    if cardinality(v_product.sizes) > 0 and not (v_line.size = any(v_product.sizes)) then raise exception 'INVALID_SIZE'; end if;
    if jsonb_array_length(v_product.colors) > 0 then
      if not exists (select 1 from jsonb_array_elements(v_product.colors) c where c->>'name' = v_line.color) then
        raise exception 'INVALID_COLOR';
      end if;
    elsif v_line.color <> '' then
      raise exception 'INVALID_COLOR';
    end if;

    if jsonb_array_length(v_product.variants) > 0 then
      select (e->>'stock')::integer into v_vstock from jsonb_array_elements(v_product.variants) e
       where e->>'color' = v_line.color and e->>'size' = v_line.size;
      if not found then raise exception 'INVALID_VARIANT'; end if;
      if v_vstock < v_line.quantity then raise exception 'OUT_OF_STOCK'; end if;
      v_new := public.krypto_variant_adjust(v_product.variants, v_line.color, v_line.size, -v_line.quantity);
      update public.products set variants = v_new,
        stock = (select coalesce(sum((e->>'stock')::integer), 0) from jsonb_array_elements(v_new) e)
       where id = v_product.id;
    else
      if v_product.stock < v_line.quantity then raise exception 'OUT_OF_STOCK'; end if;
      update public.products set stock = stock - v_line.quantity where id = v_product.id;
    end if;

    v_subtotal := v_subtotal + v_product.price_cents * v_line.quantity;
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id, 'name', v_product.name, 'quantity', v_line.quantity, 'size', v_line.size,
      'color', v_line.color,
      'unit_price_cents', v_product.price_cents, 'weight_grams', v_product.weight_grams
    ));
  end loop;

  if p_pix_discount_percent is not null and p_pix_discount_percent > 0 then
    v_discount := round(v_subtotal * least(p_pix_discount_percent, 50) / 100)::integer;
  end if;
  v_total := v_subtotal - v_discount + p_shipping_cents;
  insert into public.orders (
    customer_name, email, phone, address, address_number, complement, city, state, postal_code,
    items, subtotal_cents, shipping_cents, discount_cents, total_cents, status, payment_status,
    privacy_policy_acknowledged_at, privacy_policy_version, user_id
  ) values (
    left(trim(p_customer->>'name'),160), left(trim(p_customer->>'email'),254), left(trim(p_customer->>'phone'),40),
    left(trim(p_customer->>'address'),200), left(trim(p_customer->>'address_number'),30),
    left(coalesce(trim(p_customer->>'complement'),''),120), left(trim(p_customer->>'city'),100),
    left(trim(p_customer->>'state'),60), left(trim(p_customer->>'postal_code'),20),
    v_items, v_subtotal, p_shipping_cents, v_discount, v_total, 'aguardando_pagamento', 'pending', now(), '1.0', p_user_id
  ) returning orders.public_id into v_public_id;

  return query select v_public_id, v_total, v_subtotal, p_shipping_cents, v_discount, v_items;
end;
$$;
revoke all on function public.create_krypto_order_v2(jsonb,jsonb,integer,boolean,uuid,numeric) from public, anon, authenticated;
grant execute on function public.create_krypto_order_v2(jsonb,jsonb,integer,boolean,uuid,numeric) to service_role;
