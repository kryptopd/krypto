-- Execute no SQL Editor do Supabase. Pode rodar mais de uma vez.

-- 1) Até 4 fotos por produto. image_url continua sendo a capa (primeira foto) para a sacola e o checkout.
alter table public.products add column if not exists images text[] not null default '{}';
update public.products set images = array[image_url] where cardinality(images) = 0 and coalesce(image_url, '') <> '';
alter table public.products drop constraint if exists products_images_max4;
alter table public.products add constraint products_images_max4 check (cardinality(images) <= 4);

-- 2) A categoria deixa de ser uma lista fixa: agora vem da tabela "categories" (ou fica vazia = sem categoria).
alter table public.products drop constraint if exists products_category_check;
alter table public.products alter column category set default '';

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  created_at timestamptz not null default now()
);
create unique index if not exists categories_name_lower_key on public.categories (lower(name));
alter table public.categories enable row level security;
drop policy if exists "No public category access" on public.categories;

-- Categorias que já existiam nos produtos (e as três antigas) viram categorias editáveis.
insert into public.categories (name)
select distinct name from (
  select category as name from public.products where coalesce(category, '') <> ''
  union select 'Camisetas' union select 'Moletons' union select 'Acessórios'
) c
on conflict do nothing;

-- 3) Pasta pública das fotos. (A API também cria a pasta sozinha no primeiro envio, se não existir.)
do $$
begin
  insert into storage.buckets (id, name, public) values ('product-images', 'product-images', true)
  on conflict (id) do update set public = true;
exception when others then
  raise notice 'Não foi possível criar a pasta product-images aqui; a API cria no primeiro envio de foto.';
end $$;
