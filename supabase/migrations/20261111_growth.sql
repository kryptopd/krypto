-- KRYPTO: contas de clientes próprias, linha do tempo do pedido, e-mails de interessados, preço "de/por",
-- composição/cuidados, destaque, lançamento agendado e cupom registrado no pedido.
-- Só acréscimos (nada é apagado). Pode rodar mais de uma vez.

-- 1) Produto: preço original ("de"), composição, cuidados, destaque e lançamento agendado.
alter table public.products add column if not exists compare_at_cents integer;
alter table public.products add column if not exists composition text not null default '';
alter table public.products add column if not exists care text not null default '';
alter table public.products add column if not exists featured boolean not null default false;
alter table public.products add column if not exists publish_at timestamptz;

-- 2) Pedido: cupom usado e frete escolhido.
alter table public.orders add column if not exists coupon_code text not null default '';
alter table public.orders add column if not exists shipping_service text not null default '';
alter table public.orders add column if not exists shipping_days integer;

-- 3) Contas de clientes (login próprio, sem depender do Supabase Auth e dos limites de e-mail dele).
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  email text not null check (char_length(email) <= 254),
  password_hash text not null,
  name text not null default '',
  phone text not null default '',
  address jsonb not null default '{}'::jsonb,
  favorites jsonb not null default '[]'::jsonb,
  failed_logins integer not null default 0,
  locked_until timestamptz,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index if not exists customers_email_key on public.customers (lower(email));
alter table public.customers enable row level security;
-- Sem policies: só a API (service_role) lê e grava.

-- 4) Linha do tempo do pedido.
create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status text not null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists order_events_order_idx on public.order_events (order_id, created_at);
alter table public.order_events enable row level security;

create or replace function public.krypto_log_order_event()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (order_id, status, note) values (new.id, 'criado', '');
    return new;
  end if;
  if new.status is distinct from old.status then
    insert into public.order_events (order_id, status, note)
    values (new.id, new.status,
      case when new.status = 'enviado' and coalesce(new.tracking_code, '') <> ''
        then trim(coalesce(new.shipping_provider, '') || ' ' || new.tracking_code) else '' end);
  elsif new.payment_status is distinct from old.payment_status and new.payment_status = 'approved' then
    insert into public.order_events (order_id, status, note) values (new.id, 'pago', '');
  elsif new.status = 'enviado' and new.tracking_code is distinct from old.tracking_code and coalesce(new.tracking_code, '') <> '' then
    insert into public.order_events (order_id, status, note)
    values (new.id, 'rastreio', trim(coalesce(new.shipping_provider, '') || ' ' || new.tracking_code));
  end if;
  return new;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_trigger where tgname = 'krypto_log_order_event_trg') then
    create trigger krypto_log_order_event_trg after insert or update of status, payment_status, tracking_code on public.orders
      for each row execute function public.krypto_log_order_event();
  end if;
end $$;

-- 5) Interessados (newsletter / cupom de boas-vindas), com consentimento.
create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text not null check (char_length(email) <= 254),
  source text not null default 'site',
  created_at timestamptz not null default now()
);
create unique index if not exists subscribers_email_key on public.subscribers (lower(email));
alter table public.subscribers enable row level security;
