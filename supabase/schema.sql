create or replace function public.create_krypto_order(
  p_customer jsonb, p_item jsonb, p_shipping_cents integer default 0, p_privacy_acknowledged boolean default false
)
returns table(public_id text, total_cents integer, subtotal_cents integer, shipping_cents integer, item_name text, unit_price_cents integer)
language plpgsql security definer set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_quantity integer;
  v_size text;
  v_subtotal integer;
  v_total integer;
  v_public_id text;
begin
  v_quantity := (p_item->>'quantity')::integer;
  v_size := coalesce(p_item->>'size', '');
  if v_quantity < 1 or v_quantity > 10 then raise exception 'INVALID_QUANTITY'; end if;
  if p_shipping_cents is null or p_shipping_cents < 0 or p_shipping_cents > 1000000 then raise exception 'INVALID_SHIPPING'; end if;
  if p_privacy_acknowledged is distinct from true then raise exception 'PRIVACY_CONSENT_REQUIRED'; end if;

  select * into v_product from public.products
   where id = (p_item->>'product_id')::bigint and active = true for update;
  if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
  if v_product.stock < v_quantity then raise exception 'OUT_OF_STOCK'; end if;
  if cardinality(v_product.sizes) > 0 and not (v_size = any(v_product.sizes)) then raise exception 'INVALID_SIZE'; end if;

  v_subtotal := v_product.price_cents * v_quantity;
  v_total := v_subtotal + p_shipping_cents;
  insert into public.orders (
    customer_name, email, phone, address, address_number, complement, city, state, postal_code,
    items, subtotal_cents, shipping_cents, total_cents, status, payment_status, privacy_policy_acknowledged_at, privacy_policy_version
  ) values (
    left(trim(p_customer->>'name'),160), left(trim(p_customer->>'email'),254), left(trim(p_customer->>'phone'),40),
    left(trim(p_customer->>'address'),200), left(trim(p_customer->>'address_number'),30),
    left(coalesce(trim(p_customer->>'complement'),''),120), left(trim(p_customer->>'city'),100),
    left(trim(p_customer->>'state'),60), left(trim(p_customer->>'postal_code'),20),
    jsonb_build_array(jsonb_build_object(
      'product_id',v_product.id,'name',v_product.name,'quantity',v_quantity,'size',v_size,
      'unit_price_cents',v_product.price_cents
    )), v_subtotal, p_shipping_cents, v_total, 'aguardando_pagamento', 'pending', now(), '1.0'
  ) returning orders.public_id into v_public_id;
  update public.products set stock = stock - v_quantity where id = v_product.id;
  return query select v_public_id, v_total, v_subtotal, p_shipping_cents, v_product.name, v_product.price_cents;
end;
$$;
revoke all on function public.create_krypto_order(jsonb,jsonb,integer,boolean) from public, anon, authenticated;
grant execute on function public.create_krypto_order(jsonb,jsonb,integer,boolean) to service_role;

create or replace function public.cancel_krypto_order(p_public_id text, p_reason text default 'cancelled')
returns table(refund_required boolean, order_status text)
language plpgsql security definer set search_path = public
as $$
declare v_order public.orders%rowtype; v_item jsonb;
begin
  select * into v_order from public.orders where public_id = p_public_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if v_order.payment_status = 'approved' then
    return query select true, v_order.status;
    return;
  end if;
  if not v_order.inventory_released then
    for v_item in select value from jsonb_array_elements(v_order.items) loop
      update public.products set stock = stock + greatest(0, coalesce((v_item->>'quantity')::integer,0))
       where id = (v_item->>'product_id')::bigint;
    end loop;
  end if;
  update public.orders set status = 'cancelado', payment_status = case when p_reason = 'payment_setup_failed' then 'cancelled' else payment_status end,
    inventory_released = true, updated_at = now()
   where id = v_order.id;
  return query select false, 'cancelado'::text;
end;
$$;
revoke all on function public.cancel_krypto_order(text,text) from public, anon, authenticated;
grant execute on function public.cancel_krypto_order(text,text) to service_role;

create or replace function public.apply_krypto_payment(
  p_public_id text, p_payment_id text, p_payment_status text, p_amount_cents integer
)
returns table(refund_required boolean, order_status text)
language plpgsql security definer set search_path = public
as $$
declare v_order public.orders%rowtype; v_item jsonb;
begin
  if p_payment_status not in ('approved','rejected','cancelled','refunded','charged_back','pending') then
    raise exception 'INVALID_PAYMENT_STATUS';
  end if;
  select * into v_order from public.orders where public_id = p_public_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if p_amount_cents is distinct from v_order.total_cents then raise exception 'PAYMENT_AMOUNT_MISMATCH'; end if;

  if p_payment_status = 'approved' then
    if v_order.status in ('cancelado','expirado') or v_order.inventory_released then
      update public.orders set payment_status='approved', mp_payment_id=p_payment_id, updated_at=now() where id=v_order.id;
      return query select true, v_order.status;
      return;
    end if;
    update public.orders set payment_status='approved', mp_payment_id=p_payment_id,
      status=case when status in ('aguardando','aguardando_pagamento') then 'confirmado' else status end,
      updated_at=now() where id=v_order.id;
    return query select false, 'confirmado'::text;
    return;
  end if;

  if p_payment_status in ('rejected','cancelled') then
    if not v_order.inventory_released then
      for v_item in select value from jsonb_array_elements(v_order.items) loop
        update public.products set stock = stock + greatest(0, coalesce((v_item->>'quantity')::integer,0))
         where id = (v_item->>'product_id')::bigint;
      end loop;
    end if;
    update public.orders set payment_status=p_payment_status, mp_payment_id=p_payment_id,
      status='cancelado', inventory_released=true, updated_at=now() where id=v_order.id;
    return query select false, 'cancelado'::text;
    return;
  end if;

  if p_payment_status in ('refunded','charged_back') then
    if not v_order.inventory_released and v_order.status not in ('enviado','entregue') then
      for v_item in select value from jsonb_array_elements(v_order.items) loop
        update public.products set stock = stock + greatest(0, coalesce((v_item->>'quantity')::integer,0))
         where id = (v_item->>'product_id')::bigint;
      end loop;
    end if;
    update public.orders set payment_status=p_payment_status,
      status=case when status in ('enviado','entregue') then status else 'cancelado' end,
      inventory_released=case when status in ('enviado','entregue') then inventory_released else true end,
      mp_payment_id=p_payment_id, updated_at=now() where id=v_order.id;
    return query select false, v_order.status;
    return;
  end if;

  update public.orders set payment_status='pending', mp_payment_id=p_payment_id, updated_at=now() where id=v_order.id;
  return query select false, v_order.status;
end;
$$;
revoke all on function public.apply_krypto_payment(text,text,text,integer) from public, anon, authenticated;
grant execute on function public.apply_krypto_payment(text,text,text,integer) to service_role;

create or replace function public.expire_krypto_orders()
returns integer language plpgsql security definer set search_path = public
as $$
declare v_order public.orders%rowtype; v_item jsonb; v_count integer := 0;
begin
  for v_order in select * from public.orders
    where status='aguardando_pagamento' and payment_status in ('pending','rejected') and created_at < now() - interval '30 minutes'
    and inventory_released=false
    for update skip locked
  loop
    for v_item in select value from jsonb_array_elements(v_order.items) loop
      update public.products set stock = stock + greatest(0, coalesce((v_item->>'quantity')::integer,0))
       where id = (v_item->>'product_id')::bigint;
    end loop;
    update public.orders set status='expirado', payment_status='expired', inventory_released=true, updated_at=now() where id=v_order.id;
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;
revoke all on function public.expire_krypto_orders() from public, anon, authenticated;
grant execute on function public.expire_krypto_orders() to service_role;

