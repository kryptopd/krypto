create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Camisetas', 'Moletons', 'Acessórios')),
  price_cents integer not null check (price_cents > 0),
  stock integer not null default 0 check (stock >= 0),
  sizes text[] not null default '{}',
  tag text not null default '',
  image_url text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  public_id text not null unique default upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 12)),
  customer_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  address_number text not null,
  complement text not null default '',
  city text not null,
  state text not null,
  postal_code text not null,
  items jsonb not null default '[]'::jsonb,
  subtotal_cents integer not null default 0 check (subtotal_cents >= 0),
  shipping_cents integer not null default 0 check (shipping_cents >= 0),
  total_cents integer not null check (total_cents >= 0),
  status text not null default 'aguardando_pagamento',
  payment_status text not null default 'pending',
  mp_preference_id text,
  mp_payment_id text,
  inventory_released boolean not null default false,
  privacy_policy_acknowledged_at timestamptz,
  privacy_policy_version text not null default '1.0',
  tracking_code text,
  shipping_provider text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

