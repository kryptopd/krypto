create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Camisetas', 'Moletons', 'Acessórios')),
  price_cents integer not null check (price_cents > 0),
  stock integer not null default 0 check (stock >= 0),
  sizes text[] not null default '{}',
  tag text not null default '',
  image_url text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  public_id text not null unique default upper(substr(encode(gen_random_bytes(5), 'hex'), 1, 8)),
  customer_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  address_number text not null,
  complement text not null default '',
  city text not null,
  state text not null,
  postal_code text not null,
  items jsonb not null default '[]'::jsonb,
  total_cents integer not null check (total_cents >= 0),
  status text not null default 'aguardando'
    check (status in ('aguardando', 'confirmado', 'enviado', 'cancelado')),
  created_at timestamptz not null default now()
);

-- O frontend nunca recebe a service role key. Todas as operações de banco passam
-- pelas funções de servidor da Vercel; RLS bloqueia acesso direto via API pública.
alter table public.products enable row level security;
alter table public.orders enable row level security;

drop policy if exists "No public product access" on public.products;
drop policy if exists "No public order access" on public.orders;

create or replace function public.create_krypto_order(p_customer jsonb, p_item jsonb)
returns table(public_id text, total_cents integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_quantity integer;
  v_size text;
  v_total integer;
  v_public_id text;
begin
  v_quantity := (p_item->>'quantity')::integer;
  v_size := coalesce(p_item->>'size', '');

  if v_quantity < 1 or v_quantity > 10 then
    raise exception 'INVALID_QUANTITY';
  end if;

  select * into v_product
    from public.products
   where id = (p_item->>'product_id')::bigint and active = true
   for update;

  if not found then
    raise exception 'PRODUCT_NOT_FOUND';
  end if;

  if v_product.stock < v_quantity then
    raise exception 'OUT_OF_STOCK';
  end if;

  if cardinality(v_product.sizes) > 0 and not (v_size = any(v_product.sizes)) then
    raise exception 'INVALID_SIZE';
  end if;

  v_total := v_product.price_cents * v_quantity;

  insert into public.orders (
    customer_name, email, phone, address, address_number, complement,
    city, state, postal_code, items, total_cents
  ) values (
    p_customer->>'name', p_customer->>'email', p_customer->>'phone',
    p_customer->>'address', p_customer->>'address_number',
    coalesce(p_customer->>'complement', ''), p_customer->>'city',
    p_customer->>'state', p_customer->>'postal_code',
    jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id, 'name', v_product.name,
      'quantity', v_quantity, 'size', v_size,
      'unit_price_cents', v_product.price_cents
    )), v_total
  ) returning orders.public_id into v_public_id;

  update public.products set stock = stock - v_quantity where id = v_product.id;

  return query select v_public_id, v_total;
end;
$$;

revoke all on function public.create_krypto_order(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.create_krypto_order(jsonb, jsonb) to service_role;

